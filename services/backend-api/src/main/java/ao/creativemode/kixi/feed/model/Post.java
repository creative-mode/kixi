package ao.creativemode.kixi.feed.model;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.Id;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.relational.core.mapping.Column;
import org.springframework.data.relational.core.mapping.Table;

import java.time.LocalDateTime;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Table("posts")
public class Post {

    @Id
    private Long id;

    @Column("author_account_id")
    private Long authorAccountId;

    /** The hard isolation boundary: a post never crosses a school. */
    @Column("institution_id")
    private Long institutionId;

    @Column("school_year_id")
    private Long schoolYearId;

    @Column("course_id")
    private Long courseId;

    @Column("class_id")
    private Long classId;

    @Column("type")
    private String type;

    @Column("title")
    private String title;

    @Column("content")
    private String content;

    /** Set on a SIMULATION post: the attempt it publishes and the figures taken from it at publish time. */
    @Column("simulation_id")
    private Long simulationId;

    @Column("statement_title")
    private String statementTitle;

    @Column("school_name")
    private String schoolName;

    @Column("final_score")
    private Double finalScore;

    @Column("max_score")
    private Double maxScore;

    @Column("correct_answers")
    private Integer correctAnswers;

    @Column("total_questions")
    private Integer totalQuestions;

    @Column("time_spent_seconds")
    private Integer timeSpentSeconds;

    @Column("is_auto_generated")
    private Boolean isAutoGenerated;

    @Column("is_hidden")
    private Boolean isHidden;

    @Column("hidden_by_account_id")
    private Long hiddenByAccountId;

    @Column("hidden_at")
    private LocalDateTime hiddenAt;

    @CreatedDate
    @Column("created_at")
    private LocalDateTime createdAt;

    @LastModifiedDate
    @Column("updated_at")
    private LocalDateTime updatedAt;

    @Column("deleted_at")
    private LocalDateTime deletedAt;

    public void hide(Long byAccountId, LocalDateTime at) {
        this.isHidden = true;
        this.hiddenByAccountId = byAccountId;
        this.hiddenAt = at;
    }

    public void unhide() {
        this.isHidden = false;
        this.hiddenByAccountId = null;
        this.hiddenAt = null;
    }

    public void markAsDeleted() {
        this.deletedAt = LocalDateTime.now();
    }

    public boolean isDeleted() {
        return this.deletedAt != null;
    }
}
